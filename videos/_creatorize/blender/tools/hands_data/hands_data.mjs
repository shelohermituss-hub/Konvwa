// One source of truth for hands in both engines: reads the 3D reconstruction's lib/hands.js (VERIFIED table, hand POSES,
// USES, CLIP_SHORT, BAR_BEST) and every kit prop's grips from lib/props.js (prop(kind).userData.prop: size, box, grips),
// and writes templates/blender/engine/data/hands.json, which the Blender engine's hands.py reads.
// Run after hands.js / props.js change:   node templates/blender/tools/hands_data/hands_data.mjs
import { register } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

register(new URL('./hooks.mjs', import.meta.url).href);
const HERE = path.dirname(fileURLToPath(import.meta.url)), ROOT = path.resolve(HERE, '..', '..', '..', '..');
const LIB = path.join(ROOT, 'templates', 'recon', 'lib');
// a canvas that draws nothing (a few kit props paint label textures while they build)
const ctx = new Proxy({}, { get: (t, k) => (k === 'measureText' ? () => ({ width: 10 }) : k === 'createLinearGradient' || k === 'createRadialGradient' ? () => ({ addColorStop() {} }) : () => {}), set: () => true });
globalThis.document = { createElement: () => ({ width: 0, height: 0, getContext: () => ctx, style: {} }) };

const H = await import(pathToFileURL(path.join(LIB, 'hands.js')).href);
const P = await import(pathToFileURL(path.join(LIB, 'props.js')).href);
const src = fs.readFileSync(path.join(LIB, 'hands.js'), 'utf8');
const lit = name => { const m = new RegExp(`const ${name} = (\\{[^;]*?\\});`, 's').exec(src); return m ? Function(`return (${m[1]})`)() : null; };
const r4 = v => Math.round(v * 1e4) / 1e4;
const vec = v => (Array.isArray(v) ? v.map(r4) : v);
const cleanGrip = g => { if (!g) return g; const o = {}; for (const [k, v] of Object.entries(g)) o[k] = k === 'second' ? cleanGrip(v) : k === 'bar' ? [vec(v[0]), vec(v[1]), r4(v[2])] : Array.isArray(v) && v.every(x => typeof x === 'number') ? vec(v) : v; return o; };
const props = {}, failed = [], meshes = {};
for (const kind of Object.keys(P.PROP_KINDS)) {
  let g; try { g = P.prop(kind);
    // (a laptop has grips only closed: props.js gives the open one none, so the closed build is exported)
    if (!g.userData.prop?.grips) { const g2 = P.prop(kind, { open: 0 }); if (g2.userData.prop?.grips) g = g2; } }
  catch (e) { failed.push(`${kind}: ${e.message.split('\n')[0]}`); continue; }
  const u = g.userData.prop; if (!u?.grips) continue;
  props[kind] = { size: u.size, box: u.box?.map(r4), mount: u.mount, grips: Object.fromEntries(Object.entries(u.grips).map(([k, v]) => [k, cleanGrip(v)])) };
  // the prop's exact geometry (the grips were made and verified on it), Blender axes (x, -z, y), for hands.py kit()
  g.updateMatrixWorld(true); const parts = [], v = new (await import(pathToFileURL(path.join(ROOT, 'templates', 'recon', 'vendor', 'three.module.js')).href)).Vector3();
  g.traverse(m => { if (!m.isMesh || !m.geometry?.attributes?.position) return; const pa = m.geometry.attributes.position, ix = m.geometry.index, vs = [], fs = [];
    for (let i = 0; i < pa.count; i++) { v.fromBufferAttribute(pa, i).applyMatrix4(m.matrixWorld); vs.push(r4(v.x), r4(-v.z), r4(v.y)); }
    if (ix) for (let i = 0; i < ix.count; i++) fs.push(ix.getX(i)); else for (let i = 0; i < pa.count; i++) fs.push(i);
    const mat = [].concat(m.material)[0], col = mat?.color?.getHexString?.();
    // open: hands.js propTris' rule (planes, tubes, shapes, rings, circles and userData.open parts are never "inside");
    // noHold: parts hands.js leaves out of every hand query (userData.noHold, or every material invisible)
    const open = /Plane|Tube|Shape|Ring|Circle/.test(m.geometry.type) || !!m.userData.open;
    const noHold = !!m.userData.noHold || [].concat(m.material).every(x => x && x.visible === false);
    parts.push({ name: m.name || kind, color: col ? '#' + col : '#888888', v: vs, f: fs, ...(open ? { open: true } : {}), ...(noHold ? { noHold: true } : {}) }); });
  meshes[kind] = parts;
}
fs.writeFileSync(path.join(ROOT, 'templates', 'blender', 'engine', 'data', 'kit_props.json'), JSON.stringify({ version: 1, about: 'recon kit props (lib/props.js) geometry with grips, Blender axes; generated by hands_data.mjs', props: meshes }));
const out = {
  version: 1,
  about: 'Generated by templates/blender/tools/hands_data/hands_data.mjs from templates/recon/lib/hands.js + props.js. Do not edit: change hands.js / props.js and run it again. Grip convention (props.js): pos = where the palm centre goes (prop-local, metres, origin at the footprint centre on the floor, +Y up, front +Z), fingers = the open fingers\' direction, palm = from the palm INTO the object; hand R|L|any, mirror = the axis the other hand\'s grip is mirrored across, second = the other hand of a two-hand grip.',
  clipShort: lit('CLIP_SHORT'),
  verified: H.VERIFIED,
  poses: H.POSES,
  uses: H.USES,
  barBest: lit('BAR_BEST'),
  props,
};
const dst = path.join(ROOT, 'templates', 'blender', 'engine', 'data', 'hands.json');
fs.mkdirSync(path.dirname(dst), { recursive: true });
fs.writeFileSync(dst, JSON.stringify(out, null, 1) + '\n');
const combos = Object.values(H.VERIFIED).reduce((n, row) => n + Object.values(row).reduce((m, sides) => m + Object.values(sides).reduce((k, s) => { const [sh, ...full] = s.trim().split(' '); return k + [...(s.startsWith(' ') ? '' : sh)].length + full.length + (s.startsWith(' ') ? 1 : 0); }, 0), 0), 0);
console.log(`hands.json: ${Object.keys(H.VERIFIED).length} verified kind|grip rows, ${combos} kind|grip|body|hand|clip combos, ${Object.keys(props).length} props with grips, ${Object.keys(H.POSES).length} poses, ${Object.keys(H.USES).length} uses`);
if (failed.length) console.log('props that did not build headless (no grips exported):', failed.join('; '));
