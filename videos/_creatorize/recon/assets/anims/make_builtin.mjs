// Writes builtin.json: the catalog of the built-in (CC0) character clips, from the character library's animation packs
// (templates/lowpoly/library/animations) and what its index.json says each clip is for. Tags, hands and loop come from
// lib/anims.js (the same rules the importer uses). Run after a pack changes:  node templates/recon/assets/anims/make_builtin.mjs
// (the animlib scenario fails when this file and the packs disagree).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url)), ROOT = path.resolve(HERE, '..', '..', '..', '..');
const LIB = path.join(ROOT, 'templates', 'lowpoly', 'library');
const { PACKS, builtinEntry } = await import(pathToFileURL(path.join(ROOT, 'templates', 'recon', 'lib', 'anims.js')).href);
const glbClips = f => { const b = fs.readFileSync(f), n = b.readUInt32LE(12), j = JSON.parse(b.subarray(20, 20 + n).toString());
  return (j.animations || []).map(a => ({ name: a.name, duration: Math.max(0, ...a.samplers.map(s => j.accessors[s.input].max?.[0] ?? 0)) })); };
const idx = JSON.parse(fs.readFileSync(path.join(LIB, 'index.json'), 'utf8')).entries, use = new Map();
for (const e of idx) if (/^animations\/(ual[12]|gestures|kaykit_ue)\.glb$/.test(e.file || '')) for (const c of e.animations || e.clips || []) if (!use.has(c.name)) use.set(c.name, c);
const entries = [], seen = new Set();
for (const [pack, p] of Object.entries(PACKS)) for (const c of glbClips(path.join(LIB, p.file))) {
  if (c.name === 'A_TPose' || seen.has(c.name)) continue; seen.add(c.name);
  const u = use.get(c.name), e = builtinEntry(c.name, c.duration, pack, u?.use ? { use: u.use } : {});
  if (u && typeof u.loop === 'boolean') e.loop = u.loop;
  delete e.use; entries.push(e);
}
// the QA verdicts (experiments/recon-style/src/stories/animqa: run.mjs all + grade.mjs -> quality.json): quality verified |
// ok | broken (findAnims / animClip never offer a broken clip unless asked with { allowBroken: true }), per body, notes
const QF = path.join(HERE, 'quality.json'), QA = fs.existsSync(QF) ? JSON.parse(fs.readFileSync(QF, 'utf8')).clips ?? {} : {};
for (const e of entries) { const q = QA[e.name]; if (!q) continue; e.quality = q.quality; if (q.by && Object.values(q.by).some(v => v !== q.quality)) e.qualityBy = q.by; if (q.notes) e.notes = q.notes; }
const out = { version: 1, about: 'Built-in character clips (CC0) of the 3D reconstruction figures: lib/anims.js catalog. Generated by make_builtin.mjs.', entries };
fs.writeFileSync(path.join(HERE, 'builtin.json'), JSON.stringify(out, null, 1) + '\n');
console.log('builtin.json:', entries.length, 'clips', JSON.stringify(entries.reduce((m, e) => (m[e.quality ?? 'unchecked'] = (m[e.quality ?? 'unchecked'] || 0) + 1, m), {})));
